#!/usr/bin/env python3
"""
Adds the HC03 integration to the Android project generated by `flutter create`.

Run from apps/patient_app after:
    flutter create --platforms=android --org health.rpm --project-name patient_app .

What it does (idempotent — safe to run repeatedly):
  1. copies vendor/BleDev_release_v2.7.2.aar into android/app/libs/
  2. adds the AAR dependency, minSdk 24 and ProGuard rules to android/app/build.gradle(.kts)
  3. adds Bluetooth permissions (same pattern as the vendor demo) to AndroidManifest.xml
  4. installs MainActivity.kt + Hc03Bridge.kt from android_overlay/ into the app package
  5. enables Jetifier (the vendor SDK was built against the old support library)
"""
from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

AAR_NAME = "BleDev_release_v2.7.2.aar"
MIN_SDK = 24
MARK = "RPM-HC03"

PERMISSIONS = f"""    <!-- {MARK}: Bluetooth permissions for the HC03 (pattern from the vendor demo) -->
    <uses-permission android:name="android.permission.INTERNET" />
    <uses-permission android:name="android.permission.ACCESS_NETWORK_STATE" />
    <uses-permission android:name="android.permission.BLUETOOTH" android:maxSdkVersion="30" />
    <uses-permission android:name="android.permission.BLUETOOTH_ADMIN" android:maxSdkVersion="30" />
    <uses-permission android:name="android.permission.ACCESS_FINE_LOCATION" android:maxSdkVersion="30" />
    <uses-permission android:name="android.permission.ACCESS_COARSE_LOCATION" android:maxSdkVersion="30" />
    <uses-permission android:name="android.permission.BLUETOOTH_SCAN" android:usesPermissionFlags="neverForLocation" />
    <uses-permission android:name="android.permission.BLUETOOTH_CONNECT" />
    <uses-feature android:name="android.hardware.bluetooth_le" android:required="true" />
"""

PROGUARD = f"""# {MARK}: keep the vendor SDK (JNI + reflection) intact in release builds
-keep class com.linktop.** {{ *; }}
-keep interface com.linktop.** {{ *; }}
-keep class com.neurosky.** {{ *; }}
-keep class lib.lt.** {{ *; }}
-keepclasseswithmembernames class * {{ native <methods>; }}
-dontwarn android.support.**
-dontwarn com.linktop.**
-dontwarn com.neurosky.**
"""


def fail(msg: str) -> None:
    print(f"patch_android: ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def find_build_file(app_dir: Path) -> Path:
    for name in ("build.gradle.kts", "build.gradle"):
        p = app_dir / name
        if p.exists():
            return p
    fail(f"no build.gradle(.kts) in {app_dir}")
    raise AssertionError


def package_name(build_text: str) -> str:
    m = re.search(r'namespace\s*=?\s*["\']([\w.]+)["\']', build_text) or re.search(
        r'applicationId\s*=?\s*["\']([\w.]+)["\']', build_text
    )
    if not m:
        fail("could not find namespace/applicationId in the app build file")
    return m.group(1)


def patch_build(path: Path) -> None:
    text = path.read_text()
    kts = path.suffix == ".kts"
    if MARK in text:
        print(f"  {path.name}: already patched")
        return

    # minSdk
    text, n = re.subn(r"minSdk\s*=\s*[\w.]+", f"minSdk = {MIN_SDK}", text, count=1)
    if n == 0:
        text, n = re.subn(r"minSdkVersion\s+[\w.]+", f"minSdkVersion {MIN_SDK}", text, count=1)
    if n == 0:
        fail("could not set minSdk")

    # ProGuard rules on the release build type
    rules = (
        'proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")'
        if kts
        else "proguardFiles getDefaultProguardFile('proguard-android-optimize.txt'), 'proguard-rules.pro'"
    )
    text, n = re.subn(r"(release\s*\{)", rf"\1\n            // {MARK}\n            {rules}", text, count=1)
    if n == 0:
        fail("could not find the release build type")

    # Vendor AAR dependency
    dep = (
        f'    implementation(files("libs/{AAR_NAME}"))'
        if kts
        else f"    implementation files('libs/{AAR_NAME}')"
    )
    text = text.rstrip() + f"\n\n// {MARK}: Linktop HC03 SDK\ndependencies {{\n{dep}\n}}\n"
    path.write_text(text)
    print(f"  {path.name}: minSdk {MIN_SDK}, ProGuard rules, AAR dependency")


def patch_manifest(path: Path) -> None:
    text = path.read_text()
    if MARK in text:
        print("  AndroidManifest.xml: already patched")
        return
    idx = text.find("<application")
    if idx < 0:
        fail("no <application> in AndroidManifest.xml")
    text = text[:idx] + PERMISSIONS.lstrip(" ") + "    " + text[idx:]
    text = re.sub(r'android:label="[^"]*"', 'android:label="RPM"', text, count=1)
    path.write_text(text)
    print("  AndroidManifest.xml: Bluetooth permissions")


def install_kotlin(overlay: Path, src_main: Path, package: str) -> None:
    target = src_main / "kotlin" / Path(*package.split("."))
    target.mkdir(parents=True, exist_ok=True)
    # remove any generated MainActivity elsewhere (Java or another package path)
    for old in list(src_main.rglob("MainActivity.java")) + list(src_main.rglob("MainActivity.kt")):
        if old.parent != target:
            old.unlink()
    for f in sorted(overlay.glob("*.kt")):
        (target / f.name).write_text(f.read_text().replace("__PACKAGE__", package))
        print(f"  installed {f.name} -> {target.relative_to(src_main.parent.parent)}")


def patch_gradle_properties(path: Path) -> None:
    text = path.read_text() if path.exists() else ""
    if "android.enableJetifier" not in text:
        text = text.rstrip() + f"\n# {MARK}: vendor SDK uses the legacy support library\nandroid.enableJetifier=true\n"
        path.write_text(text)
        print("  gradle.properties: Jetifier enabled")


def main() -> None:
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent
    android = root / "android"
    app = android / "app"
    if not app.exists():
        fail(f"{app} not found — run `flutter create --platforms=android .` first")

    libs = app / "libs"
    libs.mkdir(exist_ok=True)
    shutil.copy2(root / "vendor" / AAR_NAME, libs / AAR_NAME)
    print(f"  copied {AAR_NAME}")

    build = find_build_file(app)
    pkg = package_name(build.read_text())
    patch_build(build)
    (app / "proguard-rules.pro").write_text(PROGUARD)
    patch_manifest(app / "src" / "main" / "AndroidManifest.xml")
    install_kotlin(root / "android_overlay" / "kotlin", app / "src" / "main", pkg)
    patch_gradle_properties(android / "gradle.properties")
    print(f"patch_android: done (package {pkg})")


if __name__ == "__main__":
    main()
